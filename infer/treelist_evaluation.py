def evaluate_sites(
    sites: List[str],
    project_parent: str,
    model_loc: str,
    output_dir: Optional[str] = None,
    outlier_percentile: Optional[int] = None,
) -> None:
    """Evaluate treelists for one or more sites and generate summary outputs.

    This function is deliberately generic - it works for a single site as well
    as for many sites.  It produces three artefacts in output_dir (default
    project_parent):

    1. treelist_comparison_<model>.png - grouped bar chart.
    2. treelist_summary_<model>.csv - CSV table of counts and recovery.
    3. treelist_report_<model>.txt - human-readable report.

    Parameters
    ----------
    sites : List[str]
        Site codes that were processed in the current run.
    project_parent : str
        Root directory that contains {site}_INF_data folders.
    model_loc : str
        Path to the model checkpoint (used for naming the output files).
    output_dir : str, optional
        Destination directory for generated artefacts.  If omitted, the
        project_parent directory is used.
    outlier_percentile : int, optional
        Symmetric percentile filter applied to all height and crown-area
        statistics. Supported values are 95 and 99. ``None`` disables
        filtering.
    """
    if output_dir is None:
        output_dir = project_parent
    os.makedirs(output_dir, exist_ok=True)

    print("\n" + "=" * 70)
    print("TREE LIST EVALUATION")
    print("=" * 70)
    print(f"Sites: {', '.join(sites)}")
    print(f"Model: {model_loc}")
    print("Observed-coverage masking: enabled")
    print(f"Outlier filtering: {outlier_percentile or 'disabled'}")
    print("=" * 70 + "\n")

    # Gather metrics for each site
    metrics_list: List[Dict] = []
    for site in sites:
        inf_path = os.path.join(project_parent, f"{site}_INF_data")
        print(f"Processing site: {site}")
        site_metrics = _compute_site_metrics(site, inf_path, outlier_percentile)
        if site_metrics:
            metrics_list.append(site_metrics)
            print(f"  Observed:  {site_metrics['obs_count']:>6,} trees")
            print(f"  Predicted: {site_metrics['pred_count']:>6,} trees")
            mask_info = site_metrics["coverage_mask"]
            if mask_info["removed_pred_count"] > 0:
                print(
                    f"  Coverage mask: removed {mask_info['removed_pred_count']:,} "
                    f"of {mask_info['original_pred_count']:,} predicted trees"
                )
            print(f"  Recovery:  {site_metrics['recovery_rate']:.1f}%")
            if outlier_percentile is not None:
                height_obs = site_metrics["height_stats"].get("obs")
                height_pred = site_metrics["height_stats"].get("pred")
                crown_obs = site_metrics["crown_stats"].get("obs")
                crown_pred = site_metrics["crown_stats"].get("pred")
                filtered = sum(
                    stats.get("n_filtered", 0)
                    for stats in (height_obs, height_pred, crown_obs, crown_pred)
                    if stats
                )
                print(f"  Outlier filtering: {outlier_percentile}th percentile ({filtered} values removed)")
            print()
        else:
            print(f"  Skipping site {site} - missing treelist files.\n")

    if not metrics_list:
        print("Error: No valid metrics were collected. Evaluation aborted.")
        return

    # Derive a clean model name for file suffixes
    model_name = _extract_model_name(model_loc)

    # --------------------------------------------------------
    # Plotting
    # --------------------------------------------------------
    plot_path = os.path.join(output_dir, f"treelist_comparison_{model_name}.png")
    _plot_tree_counts(metrics_list, plot_path, model_name=model_name)

    # --------------------------------------------------------
    # Height and crown-area box plots
    # --------------------------------------------------------
    height_plot_path = os.path.join(output_dir, f"treelist_height_comparison_{model_name}.png")
    _plot_boxplot_comparison(
        metrics_list,
        attribute="height_stats",
        output_path=height_plot_path,
        ylabel="Tree Height (m)",
        title=f"Tree Height Distribution - Model: {model_name}",
    )

    crown_plot_path = os.path.join(output_dir, f"treelist_crown_comparison_{model_name}.png")
    _plot_boxplot_comparison(
        metrics_list,
        attribute="crown_stats",
        output_path=crown_plot_path,
        ylabel="Crown Area (m²)",
        title=f"Crown Area Distribution - Model: {model_name}",
    )

    # --------------------------------------------------------
    # CSV summary
    # --------------------------------------------------------
    summary_df = pd.DataFrame([_flatten_summary_record(metric) for metric in metrics_list])
    csv_path = os.path.join(output_dir, f"treelist_summary_{model_name}.csv")
    summary_df.to_csv(csv_path, index=False)
    print(f"Summary table saved to: {csv_path}")

    # --------------------------------------------------------
    # Text report
    # --------------------------------------------------------
    report_path = os.path.join(output_dir, f"treelist_report_{model_name}.txt")
    with open(report_path, "w") as f:
        f.write("=" * 70 + "\n")
        f.write("TREE LIST EVALUATION REPORT\n")
        f.write("=" * 70 + "\n")
        f.write(f"Model: {model_loc}\n")
        f.write(f"Sites evaluated: {len(metrics_list)}\n")
        f.write("Observed-coverage masking: Enabled\n")
        if outlier_percentile is None:
            f.write("Outlier filtering: Disabled\n")
        else:
            f.write(f"Outlier filtering: {outlier_percentile}th percentile\n")
