def _load_treelist_counts(obs_path: str, pred_path: str) -> Tuple[int, int, float]:
    """Load observation and prediction treelists and compute basic counts.

    Parameters
    ----------
    obs_path : str
        Path to the observed treelist CSV.
    pred_path : str
        Path to the predicted treelist CSV.

    Returns
    -------
    Tuple[int, int, float]
        (obs_count, pred_count, recovery_rate) where recovery_rate is
        pred_count / obs_count * 100 (or 0.0 when obs_count is zero).
    """
    try:
        obs_df = pd.read_csv(obs_path)
        pred_df = pd.read_csv(pred_path)
    except FileNotFoundError as exc:
        raise FileNotFoundError(f"Treelist file not found: {exc}")
    except Exception as exc:  # pragma: no cover - defensive
        raise RuntimeError(f"Error reading treelist CSVs: {exc}")

    obs_count = int(len(obs_df))
    pred_count = int(len(pred_df))
    recovery_rate = (pred_count / obs_count * 100) if obs_count > 0 else 0.0
    return obs_count, pred_count, recovery_rate


def _extract_model_name(model_loc: Optional[str]) -> str:
    """Build the evaluation model identifier from a checkpoint path.

    Expected checkpoint structure::

        .../lightning_logs/<model_name>/version_X/checkpoints/<checkpoint>.ckpt

    The channel is read from ``hparams.yaml`` in ``version_X`` and appended to
    the model directory name. For example, a model directory named
    ``multisite_fs_train_ae_os_train_tt_train_model`` with ``channel: base-ae``
    becomes ``fs_train_ae_os_train_tt_train_model_base_ae``.

    If the expected directory or hyperparameter file cannot be read, the
    function falls back to the most informative model path component available.
    """
    if not model_loc:
        return "unknown"

    checkpoint_path = Path(model_loc)
    try:
        # checkpoint -> checkpoints -> version_X -> model directory
        version_dir = checkpoint_path.parent.parent
        model_dir = version_dir.parent
        model_name = model_dir.name

        if not model_name or model_name == model_dir.anchor:
            return checkpoint_path.stem

        # Training logs use this prefix for multi-site model directories, but
        # it is metadata rather than part of the requested model identifier.
        if model_name.startswith("multisite_"):
            model_name = model_name[len("multisite_"):]

        hparams_path = version_dir / "hparams.yaml"
        channel = None
        if hparams_path.is_file():
            try:
                # Read only the scalar channel entry. Some Lightning hparams
                # files contain Python-specific YAML tags that safe_load cannot
                # deserialize, even though the channel entry itself is simple.
                channel_pattern = re.compile(r"^\s*channel\s*:\s*(.*?)\s*$")
                with hparams_path.open("r") as handle:
                    for line in handle:
                        match = channel_pattern.match(line)
                        if match:
                            channel = match.group(1).strip().strip("'\"")
                            break
            except Exception:
                print(f"Warning: Could not read channel from {hparams_path}")

        if channel:
            channel = str(channel).strip().replace("-", "_")
            return f"{model_name}_{channel}"

        print(f"Warning: Channel not found in {hparams_path}; using model directory name")
        return model_name
    except (OSError, IndexError):
        print(f"Warning: Could not extract model name from checkpoint path: {model_loc}")
        return checkpoint_path.stem or "unknown"


def _compute_column_stats(
    df: pd.DataFrame,
    column: str,
    outlier_percentile: Optional[int] = None,
) -> Optional[Dict[str, float]]:
    """Compute descriptive statistics for one treelist column.

    The returned statistics include the five-number summary, mean, sample
    standard deviation, and filtering counts. Values that cannot be converted
    to numeric values and missing values are excluded.
    """
    if column not in df.columns:
        print(f"Warning: Column '{column}' not found in treelist.")
        return None

    values = pd.to_numeric(df[column], errors="coerce").dropna()

    if values.empty:
        return None

    n_total = int(len(values))
    n_filtered = 0

    if outlier_percentile is not None:
        lower_quantile = (100 - outlier_percentile) / 200
        upper_quantile = 1 - lower_quantile
        lower_bound = values.quantile(lower_quantile)
        upper_bound = values.quantile(upper_quantile)
        filtered_values = values[(values >= lower_bound) & (values <= upper_bound)]
        n_filtered = n_total - len(filtered_values)
        values = filtered_values

    if values.empty:
        return None

    return {
        "min": float(values.min()),
        "q1": float(values.quantile(0.25)),
        "median": float(values.median()),
        "q3": float(values.quantile(0.75)),
        "max": float(values.max()),
        "mean": float(values.mean()),
        "std": float(values.std()),
        "n_total": n_total,
        "n_filtered": int(n_filtered),
    }


def _mask_predicted_treelist(
    pred_treelist_path: str,
    observed_chm_path: str,
) -> Tuple[pd.DataFrame, Dict[str, int]]:
    """Retain predicted trees located in valid observed-CHM pixels.

    The source predicted treelist is only read; it is never modified. The
    returned dataframe is written by the caller as the evaluation treelist.
    """
    pred_df = pd.read_csv(pred_treelist_path)
    original_count = len(pred_df)

    required_columns = {"tree_x", "tree_y"}
    if not required_columns.issubset(pred_df.columns):
        raise ValueError(
            "Predicted treelist must contain tree_x and tree_y columns "
            "to apply observed-coverage masking."
        )

    with rasterio.open(observed_chm_path) as observed_src:
        observed_data = observed_src.read(1, masked=True)
        valid_mask = ~np.ma.getmaskarray(observed_data)
        valid_mask &= np.isfinite(np.ma.getdata(observed_data))
        transform = observed_src.transform

        x_values = pd.to_numeric(pred_df["tree_x"], errors="coerce").to_numpy()
        y_values = pd.to_numeric(pred_df["tree_y"], errors="coerce").to_numpy()
        columns, rows = (~transform) * (x_values, y_values)
        rows = np.floor(rows).astype(np.int64)
        columns = np.floor(columns).astype(np.int64)

        in_bounds = (
            (rows >= 0)
            & (rows < valid_mask.shape[0])
            & (columns >= 0)
            & (columns < valid_mask.shape[1])
        )
        valid_tree_locations = np.zeros(len(pred_df), dtype=bool)
        valid_tree_locations[in_bounds] = valid_mask[rows[in_bounds], columns[in_bounds]]

    masked_df = pred_df.loc[valid_tree_locations].copy()
    return masked_df, {
        "original_pred_count": int(original_count),
        "masked_pred_count": int(len(masked_df)),
        "removed_pred_count": int(original_count - len(masked_df)),
    }


def _compute_site_metrics(
    site: str,
    inf_data_path: str,
    outlier_percentile: Optional[int] = None,
) -> Optional[Dict]:
    """Compute metrics for a single site.

    Parameters
    ----------
    site : str
        Site identifier (e.g. "fs").
    inf_data_path : str
        Path to the {site}_INF_data directory containing obs/ and
        pred/ sub-folders.

    Returns
    -------
    dict or None
        Dictionary with metric values or None when required files are
        missing.
    """
    obs_treelist = os.path.join(inf_data_path, "obs", "obs_treelist.csv")
    pred_treelist = os.path.join(inf_data_path, "pred", "pred_treelist.csv")
    observed_chm = os.path.join(inf_data_path, "obs", f"{site}_merged_CHM_inf.tif")
    masked_pred_treelist = os.path.join(inf_data_path, "pred", "pred_treelist_masked.csv")

    if not os.path.exists(obs_treelist):
        print(f"Warning: Observed treelist not found for site {site}")
        return None
    if not os.path.exists(pred_treelist):
        print(f"Warning: Predicted treelist not found for site {site}")
        return None

    try:
        obs_df = pd.read_csv(obs_treelist)
        if not os.path.exists(observed_chm):
            raise FileNotFoundError(f"Observed CHM not found: {observed_chm}")
        pred_df, mask_info = _mask_predicted_treelist(pred_treelist, observed_chm)
        pred_df.to_csv(masked_pred_treelist, index=False)
    except Exception as exc:
        raise RuntimeError(f"Error reading treelists for site {site}: {exc}") from exc

    obs_count = int(len(obs_df))
    pred_count = int(len(pred_df))
    recovery = (pred_count / obs_count * 100) if obs_count > 0 else 0.0

    return {
        "site": site,
        "obs_count": obs_count,
        "pred_count": pred_count,
        "recovery_rate": recovery,
        "coverage_mask": mask_info,
        "height_stats": {
            "obs": _compute_column_stats(obs_df, "tree_height_m", outlier_percentile),
            "pred": _compute_column_stats(pred_df, "tree_height_m", outlier_percentile),
        },
        "crown_stats": {
            "obs": _compute_column_stats(obs_df, "crown_area_m2", outlier_percentile),
            "pred": _compute_column_stats(pred_df, "crown_area_m2", outlier_percentile),
        },
        "obs_path": obs_treelist,
        "pred_path": pred_treelist,
        "pred_eval_path": masked_pred_treelist,
    }


