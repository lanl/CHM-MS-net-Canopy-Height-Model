"""
Tree list evaluation for CHM inference comparison.

This module provides a single public function evaluate_sites which works for
any number of sites (including a single site).  It loads the observed and
predicted treelist CSV files generated by cloud2trees, computes basic tree
count metrics, and produces a grouped bar chart visualising observed vs.
predicted tree counts as well as the recovery rate for each site.  The results
are saved as a PNG plot, a CSV summary table, and a plain-text report.

The design is intentionally lightweight - additional metrics (height, crown
area, spatial error, etc.) can be added later by extending the helper functions
inside this file without altering the public API.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from typing import List, Dict, Optional, Tuple

import pandas as pd
import matplotlib.pyplot as plt
import numpy as np
import rasterio

