def _plot_tree_counts(metrics: List[Dict], output_path: str, model_name: Optional[str] = None, title: Optional[str] = None) -> None:
    """Generate a grouped bar chart of observed/predicted counts and recovery.

    Parameters
    ----------
    metrics : List[Dict]
        List of metric dictionaries returned by _compute_site_metrics.
    output_path : str
        Destination file for the PNG plot.
    model_name : str, optional
        Model identifier to include in the title.
    title : str, optional
        Custom title (overrides the default/model name).
    """
    if not metrics:
        print("Warning: No metrics to plot.")
        return

    sites = [m["site"] for m in metrics]
    obs_counts = [m["obs_count"] for m in metrics]
    pred_counts = [m["pred_count"] for m in metrics]
    recovery_rates = [m["recovery_rate"] for m in metrics]

    # Figure with two sub‑plots: counts and recovery rate
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(max(10, len(sites) * 1.5), 10))

    # --- Counts bar chart ------------------------------------------------
    x = np.arange(len(sites))
    width = 0.35
    bars_obs = ax1.bar(x - width / 2, obs_counts, width, label="Observed", color="#2E86AB", alpha=0.8)
    bars_pred = ax1.bar(x + width / 2, pred_counts, width, label="Predicted", color="#A23B72", alpha=0.8)

    # Labels on top of bars
    for bars in (bars_obs, bars_pred):
        for bar in bars:
            height = bar.get_height()
            ax1.text(bar.get_x() + bar.get_width() / 2, height,
                     f"{int(height):,}", ha="center", va="bottom", fontsize=9)

    ax1.set_ylabel("Tree Count", fontsize=12)
    ax1.set_xlabel("Site", fontsize=12)
    ax1.set_xticks(x)
    ax1.set_xticklabels(sites, rotation=45, ha="right", fontsize=12)
    ax1.legend(loc="upper left", fontsize=10)
    ax1.grid(axis="y", alpha=0.3)

    if title:
        ax1.set_title(title, fontsize=14, weight="bold", pad=20)
    elif model_name:
        ax1.set_title(f"Tree Count Comparison - Model: {model_name}", fontsize=14, weight="bold", pad=20)
    else:
        ax1.set_title("Tree Count Comparison Across Sites", fontsize=14, weight="bold", pad=20)

    # --- Recovery rate bar chart -----------------------------------------
    bars_rec = ax2.bar(x, recovery_rates, color="#06A77D", alpha=0.8)
    # Colour‑code by performance thresholds
    for bar, rate in zip(bars_rec, recovery_rates):
        if rate >= 90:
            bar.set_color("#06A77D")  # green - excellent
        elif rate >= 70:
            bar.set_color("#F18F01")  # orange - good
        else:
            bar.set_color("#D90429")  # red - needs improvement
    # Labels on top
    for bar, rate in zip(bars_rec, recovery_rates):
        height = bar.get_height()
        ax2.text(bar.get_x() + bar.get_width() / 2, height,
                 f"{rate:.1f}%", ha="center", va="bottom", fontsize=9)

    ax2.axhline(y=100, color="gray", linestyle="--", alpha=0.5, linewidth=1)
    ax2.set_ylabel("Recovery Rate (%)", fontsize=12)
    ax2.set_xlabel("Site", fontsize=12)
    ax2.set_xticks(x)
    ax2.set_xticklabels(sites, rotation=45, ha="right", fontsize=12)
    ax2.set_title("Tree Recovery Rate by Site", fontsize=12, weight="bold", pad=10)
    ax2.grid(axis="y", alpha=0.3)

    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"Tree count comparison plot saved to: {output_path}")


def _plot_boxplot_comparison(
    metrics: List[Dict],
    attribute: str,
    output_path: str,
    ylabel: str,
    title: str,
) -> None:
    """Generate grouped observed/predicted box plots for one attribute.

    The box and whiskers use the retained minimum, Q1, median, Q3, and maximum
    values. Mean values are overlaid as diamond markers. All valid values are
    retained in the statistics; no outlier filtering is currently performed.
    """
    valid_metrics = [
        metric for metric in metrics
        if metric.get(attribute)
        and metric[attribute].get("obs")
        and metric[attribute].get("pred")
    ]
    if not valid_metrics:
        print(f"Warning: No valid {attribute} statistics available for plotting.")
        return

    sites = [metric["site"] for metric in valid_metrics]
    positions_obs = np.arange(len(sites)) * 2.5
    positions_pred = positions_obs + 1.0

    def box_stats(stats: Dict[str, float]) -> Dict[str, float]:
        return {
            "whislo": stats["min"],
            "q1": stats["q1"],
            "med": stats["median"],
            "q3": stats["q3"],
            "whishi": stats["max"],
        }

    obs_stats = [box_stats(metric[attribute]["obs"]) for metric in valid_metrics]
    pred_stats = [box_stats(metric[attribute]["pred"]) for metric in valid_metrics]

    fig, ax = plt.subplots(figsize=(max(10, len(sites) * 2), 8))
    observed_boxes = ax.bxp(
        obs_stats,
        positions=positions_obs,
        widths=0.8,
        patch_artist=True,
        showfliers=False,
        boxprops={"facecolor": "#2E86AB", "alpha": 0.7, "edgecolor": "black"},
        medianprops={"color": "black", "linewidth": 2},
        whiskerprops={"color": "black", "linewidth": 1.5},
        capprops={"color": "black", "linewidth": 1.5},
    )
    predicted_boxes = ax.bxp(
        pred_stats,
        positions=positions_pred,
        widths=0.8,
        patch_artist=True,
        showfliers=False,
        boxprops={"facecolor": "#A23B72", "alpha": 0.7, "edgecolor": "black"},
        medianprops={"color": "black", "linewidth": 2},
        whiskerprops={"color": "black", "linewidth": 1.5},
        capprops={"color": "black", "linewidth": 1.5},
    )

    for index, metric in enumerate(valid_metrics):
        ax.scatter(
            positions_obs[index], metric[attribute]["obs"]["mean"],
            color="white", marker="D", s=70, zorder=3,
            edgecolors="black", linewidths=1.2,
        )
        ax.scatter(
            positions_pred[index], metric[attribute]["pred"]["mean"],
            color="white", marker="D", s=70, zorder=3,
            edgecolors="black", linewidths=1.2,
        )

    from matplotlib.lines import Line2D
    from matplotlib.patches import Patch

    ax.set_xticks((positions_obs + positions_pred) / 2)
    ax.set_xticklabels(sites, rotation=45, ha="right", fontsize=12)
    ax.set_ylabel(ylabel, fontsize=12)
    ax.set_xlabel("Site", fontsize=12)
    ax.set_title(title, fontsize=14, weight="bold")
    ax.legend(
        handles=[
            Patch(facecolor="#2E86AB", alpha=0.7, edgecolor="black", label="Observed"),
            Patch(facecolor="#A23B72", alpha=0.7, edgecolor="black", label="Predicted"),
            Line2D([0], [0], marker="D", color="white", markerfacecolor="white",
                   markeredgecolor="black", markersize=7, label="Mean"),
        ],
        loc="upper right",
    )
    ax.grid(axis="y", alpha=0.3, linestyle="--")

    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"{ylabel} comparison plot saved to: {output_path}")


def _flatten_summary_record(metric: Dict) -> Dict:
    """Flatten nested site statistics into one CSV-compatible record."""
    record = {
        "site": metric["site"],
        "obs_count": metric["obs_count"],
        "pred_count": metric["pred_count"],
        "recovery_rate": metric["recovery_rate"],
    }
    for prefix, stats_group in (
        ("height", metric.get("height_stats", {})),
        ("crown_area", metric.get("crown_stats", {})),
    ):
        for source in ("obs", "pred"):
            stats = stats_group.get(source)
            if stats:
                for name in ("min", "q1", "median", "q3", "max", "mean", "std", "n_total", "n_filtered"):
                    record[f"{prefix}_{source}_{name}"] = stats[name]
            else:
                for name in ("min", "q1", "median", "q3", "max", "mean", "std", "n_total", "n_filtered"):
                    record[f"{prefix}_{source}_{name}"] = None
    return record


def _write_stat_report_section(file_handle, title: str, stats_group: Dict) -> None:
    """Write observed/predicted full statistics and differences to a report."""
    file_handle.write(f"{title}:\n")
    file_handle.write(f"{'Statistic':<18} {'Observed':>12} {'Predicted':>12} {'Difference':>12}\n")
    file_handle.write("-" * 58 + "\n")
    labels = (
        ("Mean", "mean"),
        ("Median", "median"),
        ("Std Dev", "std"),
        ("Min", "min"),
        ("Q1", "q1"),
        ("Q3", "q3"),
        ("Max", "max"),
    )
    observed = stats_group.get("obs")
    predicted = stats_group.get("pred")
    if not observed or not predicted:
        file_handle.write("Statistics unavailable for one or both treelists.\n\n")
        return
    for label, key in labels:
        difference = predicted[key] - observed[key]
        file_handle.write(
            f"{label + ':':<18} {observed[key]:>12.2f} {predicted[key]:>12.2f} {difference:>12.2f}\n"
        )
    file_handle.write("\n")


